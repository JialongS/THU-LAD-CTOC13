//求解J2lambert问题时的子函数，用于打靶
//输入：n为打靶变量个数，x为t0时刻输入的dv，fvec为打靶误差，iflag=1表示该段程序正常运行，
//para[0:2]表示R1，para[3:5]表示R2，para[6]表示转移时长，para[7]表示J2同伦参数
int SubFun_J2lambert(int n, const double* x, double* fvec, int iflag, const double* para)
{
	double rv0[6], rvf[6], tf, intpara[1];
	V_Copy(rv0, para, 3);
	V_Copy(&rv0[3], x, 3);
	tf = para[6];
	intpara[0] = para[7];

	iflag = orbitPropagateJ2(0, tf, rv0, rvf, intpara[0]);

	V_Minus(fvec, rvf, &para[3], 3);

	return iflag;
}

