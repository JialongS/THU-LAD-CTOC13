//求解J2lambert问题
void J2lambert(double* v1, double* v2, const double* rv1, const double* rv2, double tf,
               int& flag, double mu, int Maxiter, double tol)
{
	const int n = 3;
	double fvec[n] = {0, 0, 0}, v10[n] = {0, 0, 0};
	double para[8], wa[int((n * (3 * n + 13)) / 2)], xtol = 1.0e-8;

	//设置初值
	J2lambert_Approximation_400(v1, v2, rv1, rv2, tf, flag, mu, Maxiter, tol);
	if (flag != 1)
		V_Copy(v1, &rv1[3], 3);


	//打靶
	V_Copy(v10, v1, 3);
	V_Copy(para, rv1, 3);
	V_Copy(&para[3], rv2, 3);
	para[6] = tf;
	para[7] = 1.0;
	flag = hybrd1(SubFun_J2lambert, n, v10, fvec, para, wa, xtol, 0, Maxiter);

	if (flag == 1 && enorm(n, fvec) < tol) //打靶成功
	{
		double rv0[6], rvf[6];
		V_Copy(rv0, rv1, 3);
		V_Copy(&rv0[3], v10, 3);
		V_Copy(v1, v10, 3);
		flag = orbitPropagateJ2(0, tf, rv0, rvf, para[7]);
		if (flag != 1)
			std::cout << "积分失败" << std::endl;
		V_Copy(v2, &rvf[3], 3);
		flag = 1;
		return;
	}
	else //打靶不成功，开始同伦
	{
		const double dir = sqrt(3.0) * 100.0;
		double direction[14][3] = {
			dir, dir, dir,
			dir, dir, -dir,
			dir, -dir, dir,
			dir, -dir, -dir,
			-dir, dir, dir,
			-dir, dir, -dir,
			-dir, -dir, dir,
			-dir, -dir, -dir,
			2 * dir, 0, 0,
			-2 * dir, 0, 0,
			0, 2 * dir, 0,
			0, -2 * dir, 0,
			0, 0, 2 * dir,
			0, 0, -2 * dir
		};

		for (int i = 0; i < 14; i++)
		{
			V_Add(v10, v1, direction[i], 3);
			flag = hybrd1(SubFun_J2lambert, n, v10, fvec, para, wa, xtol, 0, Maxiter);
			if (flag == 1 && enorm(n, fvec) < tol) //打靶成功
			{
				double rv0[6], rvf[6];
				V_Copy(rv0, rv1, 3);
				V_Copy(&rv0[3], v10, 3);
				V_Copy(v1, v10, 3);
				flag = orbitPropagateJ2(0, tf, rv0, rvf, para[7]);
				if (flag != 1)
					std::cout << "积分失败" << std::endl;
				V_Copy(v2, &rvf[3], 3);
				flag = 1;

				return;
			}
		}

		std::cout << "无法同伦求解J2Lambert问题" << std::endl;
		for (int k = 0; k < 3; k++)
		{
			v1[k] = 10e10;
			v2[k] = 10e10;
		}
		flag = 2;
		return;
	}
}

/**
 * @brief solve J2 Lambert problem using MRPLPSolver
 * @param v1 return : v1 (m/s), if failed, be nan (flag = 2,3)
 * @param v2 return : v2 (m/s), if failed, be nan (flag = 2,3)
 * @param rv1 input : rv1 (m), use rv1[3:] as initial guess for v1
 * @param rv2 input : rv2 (m), only use rv2[:3]
 * @param tof input : time of flight (s)
 * @param flag return : 0 for success, 1 for reach the maxiter, 2 for fail to solve the MRPLP analyticly, 3 for non-elliptic orbit
 * @param MU input : the gravity constant (m^3/s^2)
 * @param Maxiter input : max number of iter
 * @param ftol input : max of norm(rv2[3:] - r2(got by v2))
 */
void J2_Lambert_MRPLP(double* v1, double* v2, const double* rv1, const double* rv2, double tof, int& flag, double MU,
                      int Maxiter, double ftol)
{
	int order = 4;
	std::vector<double> rr1(3), rr2(3), vv1g(3);
	for (int i = 0; i < 3; i++)
	{
		// 单位使用km，看起来更清楚
		rr1[i] = rv1[i] * 1e-3;
		rr2[i] = rv2[i] * 1e-3;
		vv1g[i] = rv1[i + 3] * 1e-3;
	}
	auto mu = MU * 1e-9;
	auto rE = RADIUS_EARTH * 1e-3;
	auto J2 = J2_EARTH;
	MultiRevolutionPerturbedLambertSolver::mrplp_J2_analytic_parameters parameters(
		rr1, rr2, tof, vv1g, mu, rE, J2, order, 1e-6, 0.0, 0.1, 1e-3, 200);
	try
	{
		flag = 1; // Maxiter reached

		// if (!DACE::DA::isInitialized())
		// 	DACE::DA::init(7, 7);

		// Solve
		auto output = MultiRevolutionPerturbedLambertSolver::mrplp_J2_analytic(parameters);
		auto vv1Sol = output.vv1Sol;
		auto vv2Sol = output.vv2Sol;
		if (!output.success)
		{
			double nan = std::numeric_limits<double>::quiet_NaN();
			for (int i = 0; i < 3; i++)
			{
				v1[i] = nan;
				v2[i] = nan;
			}
			flag = 2; // MRPLPsolver failed
			return;
		}

		// Modifiy
		parameters.order = 7;
		auto v1_modify = vv1Sol;
		std::vector<double> x0DAepxEval(6), xfDAexpEval(6);
		for (int iter = 0; iter < Maxiter; iter++)
		{
			double rv_temp1[6], rv_temp2[6];
			for (int i = 0; i < 3; i++)
			{
				rv_temp1[i] = rv1[i];
				rv_temp1[i + 3] = v1_modify[i] * 1e3;
			}
			int dflag = orbitPropagateJ2(0, tof, rv_temp1, rv_temp2);
			double drf = std::sqrt(
				(rv_temp2[0] - rv2[0]) * (rv_temp2[0] - rv2[0]) + (rv_temp2[1] - rv2[1]) * (rv_temp2[1] - rv2[1]) + (
					rv_temp2[2] - rv2[2]) * (rv_temp2[2] - rv2[2]));
			if (drf <= ftol)
			{
				flag = 0; // success
				for (int i = 0; i < 6; i++)
				{
					x0DAepxEval[i] = rv_temp1[i] * 1e-3;
					xfDAexpEval[i] = rv_temp2[i] * 1e-3;
				}
				break;
			}
			auto [x0DAepx, xfDAexp] = ExpansionPerturbedLambert::expansionOfPerturbedLambert(
				rr1, v1_modify, tof, parameters);
			std::vector<double> dX(7, 0.0);
			for (int i = 0; i < 3; i++)
			{
				dX[i + 3] = (rv2[i] - rv_temp2[i]) * 1e-3;
			}
			x0DAepxEval = x0DAepx.eval(dX);
			xfDAexpEval = xfDAexp.eval(dX);
			v1_modify.assign(x0DAepxEval.begin() + 3, x0DAepxEval.begin() + 6);
		}

		if (flag == 1) // 检查最后一次修正效果
		{
			double rv_temp1[6], rv_temp2[6];
			for (int i = 0; i < 3; i++)
			{
				rv_temp1[i] = rv1[i];
				rv_temp1[i + 1] = x0DAepxEval[i + 3] * 1e3;
			}
			int dflag = orbitPropagateJ2(0, tof, rv_temp1, rv_temp2);
			if (double drf = std::sqrt(
				(rv_temp2[0] - rv2[0]) * (rv_temp2[0] - rv2[0]) + (rv_temp2[1] - rv2[1]) * (rv_temp2[1] - rv2[1]) + (
					rv_temp2[2] - rv2[2]) * (rv_temp2[2] - rv2[2])); drf < ftol)
				flag = 0; //success
		}
		for (int i = 0; i < 3; i++)
		{
			v1[i] = x0DAepxEval[i + 3] * 1e3;
			v2[i] = xfDAexpEval[i + 3] * 1e3;
		}
		return;
	}
	catch (std::exception& e)
	{
		// std::cout << e.what() << std::endl;
		double nan = std::numeric_limits<double>::quiet_NaN();
		for (int i = 0; i < 3; i++)
		{
			v1[i] = nan;
			v2[i] = nan;
		}
		flag = 3; // The orbit is not elliptic
		return;
	}
}

